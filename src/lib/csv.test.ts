import { describe, expect, it } from "vitest";
import { toCsv } from "./csv";

const BOM = "\uFEFF";

describe("toCsv", () => {
  it("BOM 으로 시작한다", () => {
    expect(toCsv(["상품"], [])).toBe(`${BOM}"상품"\r\n`);
  });

  it("줄 끝은 CRLF 다", () => {
    expect(toCsv(["상품"], [["올스토리"]])).toBe(
      `${BOM}"상품"\r\n"올스토리"\r\n`,
    );
  });

  it("모든 칸을 따옴표로 감싼다", () => {
    expect(toCsv(["상품", "총액"], [["올스토리", "1069000"]])).toBe(
      `${BOM}"상품","총액"\r\n"올스토리","1069000"\r\n`,
    );
  });

  it("쉼표가 든 값이 칸을 쪼개지 않는다", () => {
    expect(toCsv(["상품"], [["올스토리, 정시"]])).toBe(
      `${BOM}"상품"\r\n"올스토리, 정시"\r\n`,
    );
  });

  it("값 안의 따옴표는 두 번 겹친다", () => {
    expect(toCsv(["고객명"], [['김"길동"']])).toBe(
      `${BOM}"고객명"\r\n"김""길동"""\r\n`,
    );
  });

  it("줄바꿈이 든 값도 한 칸으로 남는다", () => {
    expect(toCsv(["고객명"], [["김길동\n이순신"]])).toBe(
      `${BOM}"고객명"\r\n"김길동\n이순신"\r\n`,
    );
  });

  it("= 로 시작하는 값에 홑따옴표를 앞에 붙인다", () => {
    expect(toCsv(["고객명"], [["=1+1"]])).toBe(
      `${BOM}"고객명"\r\n"'=1+1"\r\n`,
    );
  });

  it("+ 로 시작하는 값에 홑따옴표를 앞에 붙인다", () => {
    expect(toCsv(["고객명"], [["+82 10"]])).toBe(
      `${BOM}"고객명"\r\n"'+82 10"\r\n`,
    );
  });

  it("- 로 시작하는 값에 홑따옴표를 앞에 붙인다", () => {
    expect(toCsv(["고객명"], [["-김길동"]])).toBe(
      `${BOM}"고객명"\r\n"'-김길동"\r\n`,
    );
  });

  it("@ 로 시작하는 값에 홑따옴표를 앞에 붙인다", () => {
    expect(toCsv(["고객명"], [["@김길동"]])).toBe(
      `${BOM}"고객명"\r\n"'@김길동"\r\n`,
    );
  });

  it("탭으로 시작하는 값에 홑따옴표를 앞에 붙인다", () => {
    expect(toCsv(["고객명"], [["\t=1+1"]])).toBe(
      `${BOM}"고객명"\r\n"'\t=1+1"\r\n`,
    );
  });

  it("CR 로 시작하는 값에 홑따옴표를 앞에 붙인다", () => {
    expect(toCsv(["고객명"], [["\r=1+1"]])).toBe(
      `${BOM}"고객명"\r\n"'\r=1+1"\r\n`,
    );
  });

  it("가운데에 있는 = 는 건드리지 않는다", () => {
    expect(toCsv(["고객명"], [["김=길동"]])).toBe(
      `${BOM}"고객명"\r\n"김=길동"\r\n`,
    );
  });

  it("금액은 쉼표도 원 표기도 없이 들어간다", () => {
    expect(toCsv(["총액"], [["1069000"], ["0"]])).toBe(
      `${BOM}"총액"\r\n"1069000"\r\n"0"\r\n`,
    );
  });

  it("행이 없으면 머리글만 남는다", () => {
    expect(toCsv(["요청일시", "총액"], [])).toBe(
      `${BOM}"요청일시","총액"\r\n`,
    );
  });

  it("여러 행을 CRLF 로 잇는다", () => {
    expect(
      toCsv(
        ["상품", "총액"],
        [
          ["올스토리", "1069000"],
          ["정시", "579000"],
        ],
      ),
    ).toBe(`${BOM}"상품","총액"\r\n"올스토리","1069000"\r\n"정시","579000"\r\n`);
  });
});
